# Read index.html
with open('index.html', 'r', encoding='utf-8') as f:
    html = f.read()

# Normalize whitespace and quotes for comparison
def norm(t):
    return re.sub(r'\s+', ' ', t).strip().replace('’', "'").replace('–', '-').replace('&amp;', '&')

norm_html = norm(html)

print("=== CHECKING AUDIT OF INDEX.HTML AGAINST BRIEF ===")
all_pass = True
for key, expected in brief.items():
    if key.endswith('_url'):
        found = expected in html
    else:
        found = norm(expected) in norm_html
    status = "PASS" if found else "FAIL"
    if not found:
        all_pass = False
        print(f"[{status}] {key}: NOT found!")
        print(f"   Expected: {expected[:60]}...")
    else:
        print(f"[{status}] {key}")

print("\nALL BRIEF ITEMS PASS:", all_pass)

